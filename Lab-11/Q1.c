/*================ Global =================*/
volatile uint8_t sec_ox, sec_oy, sec_nx, sec_ny;
volatile uint8_t min_ox, min_oy, min_nx, min_ny;

volatile uint8_t setting_mode = 0;   // 0: run, 1: setting
volatile uint8_t select_min = 1;     // 1: minute, 0: second

volatile int set_min = 0;
volatile int set_sec = 0;

/*================ RTC ISR =================*/
void RTC_IRQHandler(void)
{
    S_RTC_TIME_DATA_T t;
    char buf[8];
    int theta_s, theta_m;

    if (setting_mode) {
        RTC_CLEAR_TICK_INT_FLAG();
        return;
    }

    RTC_GetDateAndTime(&t);
    set_min = t.u32Minute;
    set_sec = t.u32Second;

    sprintf(buf, "%02d:%02d", set_min, set_sec);
    print_Line(0, buf);

    /* ?? */
    theta_s = t.u32Second * 6;
    sec_nx = X0 - R_SEC * cos(theta_s * PI / 180);
    sec_ny = Y0 - R_SEC * sin(theta_s * PI / 180);
    draw_Line(sec_ox, sec_oy, X0, Y0, BG_COLOR, BG_COLOR);
    draw_Line(sec_nx, sec_ny, X0, Y0, FG_COLOR, BG_COLOR);
    sec_ox = sec_nx;  sec_oy = sec_ny;

    /* ??:15 ??? */
    theta_m = (t.u32Second / 15) * 30;
    min_nx = X0 - R_MIN * cos(theta_m * PI / 180);
    min_ny = Y0 - R_MIN * sin(theta_m * PI / 180);
    draw_Line(min_ox, min_oy, X0, Y0, BG_COLOR, BG_COLOR);
    draw_Line(min_nx, min_ny, X0, Y0, FG_COLOR, BG_COLOR);
    min_ox = min_nx;  min_oy = min_ny;

    RTC_CLEAR_TICK_INT_FLAG();
}

/*================ INT1 =================*/
void EINT1_IRQHandler(void)
{
    setting_mode ^= 1;
    PC12 = setting_mode;   // ??????
    GPIO_CLR_INT_FLAG(PB, BIT15);
}

/*================ RTC Init =================*/
void Init_RTC(void)
{
    S_RTC_TIME_DATA_T t;
    t.u32Year = 2025; t.u32Month = 1; t.u32Day = 1;
    t.u32Hour = 0; t.u32Minute = 0; t.u32Second = 0;
    t.u32DayOfWeek = RTC_WEDNESDAY;
    t.u32TimeScale = RTC_CLOCK_24;

    RTC_Open(&t);
    RTC_SetTickPeriod(RTC_TICK_1_SEC);
    RTC_EnableInt(RTC_RIER_TIER_Msk);
    NVIC_EnableIRQ(RTC_IRQn);
}

